// Token Radar model "radar-2": one snapshot of the protocol universe in, one ranked board out.
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and every
// other rankable pre-token protocol the snapshot carries: the early rows the radar exists to find.
// A protocol is pre-token when its record carries no token (no market cap, no CoinGecko id, no
// symbol); the snapshot's live-token protocols are kept apart and shown as the market's own values,
// never mixed into the ranked board.
//
// Implied value follows only from the snapshot's own figures — never from a hardcoded list of names:
//
//   category multiple = the median FDV/TVL of the live-token protocols in the same category,
//                         measured on this very snapshot (n >= 3, else the global median),
//                         clamped to [0.08, 1.00]; the market's own pricing, not our guess.
//   base       = tvl_usd x category multiple
//   growth     = clamp(change_7d, -60, 120) per cent
//   growthMult = 1 + (growth / 100) x 0.6
//   maturity   = 0.65 + min(age_days, 1095) / 1095 x 0.35   (age_days unknown: 365)
//   chainsMult = 1 + 0.02 x min(chains, 5)
//   implied    = max(1, round(base x growthMult x maturity x chainsMult))
//
// A protocol "records no token" when DefiLlama's record carries none — never "has no token": the
// record is not proof, and a listed protocol may still hold a token its record does not carry.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

